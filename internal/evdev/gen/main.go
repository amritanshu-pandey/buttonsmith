// Command gen generates codes_gen.go (key/button/axis names) from the kernel
// header linux/input-event-codes.h. Run via `go generate ./internal/evdev`.
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const header = "/usr/include/linux/input-event-codes.h"

var define = regexp.MustCompile(`^#define\s+((?:KEY|BTN|REL)_[A-Z0-9_]+)\s+(\S+)`)

// Range markers that share a value with a real key; never use them as the
// display name.
var notCanonical = map[string]bool{
	"BTN_MISC": true, "BTN_MOUSE": true, "BTN_JOYSTICK": true, "BTN_GAMEPAD": true,
	"BTN_DIGI": true, "BTN_WHEEL": true, "BTN_TRIGGER_HAPPY": true,
	"KEY_MIN_INTERESTING": true, "KEY_MAX": true, "KEY_CNT": true, "REL_MAX": true, "REL_CNT": true,
}

func main() {
	f, err := os.Open(header)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	values := map[string]uint16{}
	canonical := map[uint16]string{}
	relCanonical := map[uint16]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := define.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		name, val := m[1], m[2]
		if v, ok := values[val]; ok { // alias of an earlier name
			values[name] = v
			continue
		}
		n, err := strconv.ParseUint(val, 0, 16)
		if err != nil {
			continue
		}
		values[name] = uint16(n)
		if notCanonical[name] {
			continue
		}
		if strings.HasPrefix(name, "REL_") {
			if _, ok := relCanonical[uint16(n)]; !ok {
				relCanonical[uint16(n)] = name
			}
		} else if _, ok := canonical[uint16(n)]; !ok {
			canonical[uint16(n)] = name
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by gen/main.go from " + header + "; DO NOT EDIT.\n\npackage evdev\n\n")
	b.WriteString("// keyCodes maps KEY_*/BTN_* names (including aliases) to codes.\nvar keyCodes = map[string]uint16{\n")
	for _, name := range sortedKeys(values) {
		if !strings.HasPrefix(name, "REL_") && !notCanonical[name] {
			fmt.Fprintf(&b, "\t%q: 0x%x,\n", name, values[name])
		}
	}
	b.WriteString("}\n\n// keyNames maps codes to their preferred KEY_*/BTN_* name.\nvar keyNames = map[uint16]string{\n")
	writeNames(&b, canonical)
	b.WriteString("}\n\n// relNames maps relative axis codes to REL_* names.\nvar relNames = map[uint16]string{\n")
	writeNames(&b, relCanonical)
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("codes_gen.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func sortedKeys(m map[string]uint16) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func writeNames(b *strings.Builder, m map[uint16]string) {
	codes := make([]int, 0, len(m))
	for c := range m {
		codes = append(codes, int(c))
	}
	sort.Ints(codes)
	for _, c := range codes {
		fmt.Fprintf(b, "\t0x%x: %q,\n", c, m[uint16(c)])
	}
}
